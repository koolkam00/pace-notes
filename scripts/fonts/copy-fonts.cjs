#!/usr/bin/env node
'use strict';
/**
 * The self-hosted fonts (the redesign spec, section 6.3): copies the woff2 files the site uses from
 * node_modules/@fontsource-variable into public/fonts/ (committed), and writes the @font-face rules between the
 * GENERATED markers in app/styles/fonts.css with fontsource's own unicode-range values.
 *
 *   node scripts/fonts/copy-fonts.cjs           copy the files and rewrite the @font-face block
 *   node scripts/fonts/copy-fonts.cjs --check   fail when a file or the block differs from what fontsource ships
 *
 * Three families, the Latin subsets first: Fraunces (opsz and wght axes only, upright and italic: no SOFT or WONK),
 * Inter (wght, with Cyrillic, Greek and Vietnamese for runner names) and Bricolage Grotesque (wght, the reading figure
 * only). Code on /methodology uses the device's monospace (--code), so no mono face is shipped. The family names stay the ones fontsource uses ('Fraunces Variable' …), so the font stacks
 * in app/styles/tokens.css are unchanged. URLs are /fonts/<file>: a build under NEXT_PUBLIC_BASE_PATH runs this script
 * first with that variable set, so the URLs carry the base path (app/layout.tsx preloads with it too).
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..', '..');
const SOURCE = path.join(ROOT, 'node_modules', '@fontsource-variable');
const TARGET = path.join(ROOT, 'public', 'fonts');
const CSS = path.join(ROOT, 'app', 'styles', 'fonts.css');
const START = '/* GENERATED by scripts/fonts/copy-fonts.cjs: the self-hosted faces. Do not edit by hand. */';
const END = '/* END GENERATED */';

/** [package, fontsource stylesheet, subsets (Latin first), style]. The stylesheet supplies family, weights and ranges. */
const FACES = [
  ['fraunces', 'opsz.css', ['latin', 'latin-ext'], 'normal'],
  ['fraunces', 'opsz-italic.css', ['latin', 'latin-ext'], 'italic'],
  ['inter', 'wght.css', ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext', 'greek', 'greek-ext', 'vietnamese'], 'normal'],
  ['bricolage-grotesque', 'wght.css', ['latin', 'latin-ext'], 'normal'],
];

/** The @font-face blocks of a fontsource stylesheet, keyed by file name. */
function faces(pkg, sheet) {
  const css = fs.readFileSync(path.join(SOURCE, pkg, sheet), 'utf8');
  const out = new Map();
  for (const m of css.matchAll(/@font-face\s*\{([^}]*)\}/g)) {
    const body = m[1];
    const get = (prop) => ((body.match(new RegExp(`${prop}:\\s*([^;]+);`)) || [])[1] || '').trim();
    const file = (get('src').match(/files\/([^)]+\.woff2)/) || [])[1];
    if (file) out.set(file, { family: get('font-family'), style: get('font-style'), weight: get('font-weight'), range: get('unicode-range') });
  }
  return out;
}

function plan() {
  const base = process.env.NEXT_PUBLIC_BASE_PATH || '';
  const files = [];
  const rules = [];
  for (const [pkg, sheet, subsets, style] of FACES) {
    const all = faces(pkg, sheet);
    for (const subset of subsets) {
      const file = `${pkg}-${subset}-${sheet.startsWith('opsz') ? 'opsz' : 'wght'}-${style}.woff2`;
      const face = all.get(file);
      if (!face) throw new Error(`${pkg}/${sheet} has no face for ${file}`);
      if (face.style !== style) throw new Error(`${file} is ${face.style}, expected ${style}`);
      files.push({ from: path.join(SOURCE, pkg, 'files', file), to: path.join(TARGET, file), file });
      rules.push(`@font-face { font-family: ${face.family}; font-style: ${style}; font-display: swap; font-weight: ${face.weight}; src: url(${base}/fonts/${file}) format('woff2'); unicode-range: ${face.range}; }`);
    }
  }
  return { files, block: [START, ...rules, END].join('\n') };
}

function main() {
  const check = process.argv.includes('--check');
  const { files, block } = plan();
  const css = fs.readFileSync(CSS, 'utf8');
  const at = css.indexOf(START), end = css.indexOf(END);
  const problems = [];
  for (const f of files) {
    const same = fs.existsSync(f.to) && Buffer.compare(fs.readFileSync(f.from), fs.readFileSync(f.to)) === 0;
    if (same) continue;
    if (check) problems.push(`public/fonts/${f.file} is missing or differs from fontsource`);
    else { fs.mkdirSync(TARGET, { recursive: true }); fs.copyFileSync(f.from, f.to); }
  }
  const extra = fs.existsSync(TARGET) ? fs.readdirSync(TARGET).filter((n) => n.endsWith('.woff2') && !files.some((f) => f.file === n)) : [];
  if (extra.length) problems.push(`public/fonts holds files the site does not use: ${extra.join(', ')}`);
  const current = at >= 0 && end > at ? css.slice(at, end + END.length) : null;
  if (current !== block) {
    if (check) problems.push('app/styles/fonts.css @font-face block differs from fontsource (run node scripts/fonts/copy-fonts.cjs)');
    else fs.writeFileSync(CSS, current === null ? `${block}\n\n${css}` : css.replace(current, block));
  }
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  const latin = files.filter((f) => /-latin-(?:opsz|wght)/.test(f.file)).reduce((n, f) => n + fs.statSync(f.from).size, 0);
  console.log(`${check ? 'Fonts match fontsource' : 'Fonts written'}: ${files.length} files in public/fonts, Latin faces ${(latin / 1000).toFixed(1)} kB.`);
}

main();
